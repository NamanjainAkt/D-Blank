// Helper function to get icon component from emoji
export function getIconFromEmoji(emoji: string) {
  const iconKey = emojiToIcon[emoji as keyof typeof emojiToIcon];
  return iconKey ? Icons[iconKey as keyof typeof Icons] : null;
}

// Helper function to render icon
export function renderIcon(iconKey: keyof typeof Icons, props: any = {}) {
  const IconComponent = Icons[iconKey];
  return IconComponent ? <IconComponent {...props} /> : null;
}